CREATE TABLE shard_messages (
  role         text        NOT NULL,
  entity_type  text        NOT NULL,
  shard_id     integer     NOT NULL,
  entity_id    text        NOT NULL,
  delivery_key text        NOT NULL,
  -- the order in which the messages were stored
  position     bigint      GENERATED BY DEFAULT AS IDENTITY,
  state        text        NOT NULL CHECK (state IN ('pending', 'success', 'failure', 'dead_letter')),
  -- the message, kept while it is pending and for a dead letter
  body         bytea       NOT NULL,
  -- the reply or typed error, or the reason of a dead letter
  result       bytea,
  -- null for a pending message and a dead letter, which don't expire
  expires_at   timestamptz,
  PRIMARY KEY (role, entity_type, shard_id, entity_id, delivery_key)
);

CREATE INDEX shard_messages_by_state ON shard_messages (role, entity_type, state, shard_id, position);

CREATE INDEX shard_messages_by_expiry ON shard_messages (expires_at) WHERE expires_at IS NOT NULL;
